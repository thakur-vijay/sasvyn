import SwiftUI

public enum SVFont {

    // MARK: - Large Text

    /// Large prominent titles.
    public static let largeTitle = Font.largeTitle

    /// Primary screen titles.
    public static let title = Font.title

    /// Secondary screen or section titles.
    public static let title2 = Font.title2

    /// Smaller section titles.
    public static let title3 = Font.title3

    // MARK: - Headings

    /// Primary headings and important section titles.
    public static let headline = Font.headline

    /// Secondary headings and supporting titles.
    public static let subheadline = Font.subheadline

    // MARK: - Body

    /// Standard readable content.
    public static let body = Font.body

    /// Slightly smaller body content.
    public static let callout = Font.callout

    // MARK: - Supporting Text

    /// Secondary supporting content.
    public static let footnote = Font.footnote

    /// Small metadata and supplementary information.
    public static let caption = Font.caption

    /// Smallest standard text style.
    public static let caption2 = Font.caption2
}
